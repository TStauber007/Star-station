// Dev: pause, resume and replay with real narration.
import { chromium } from '@playwright/test';
import { serveDist } from '../verify/serve.ts';
const { url, server } = await serveDist();
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1024, height: 768 } });
p.on('pageerror', (e) => console.log('PAGEERROR', String(e)));
await p.goto(url + '/');
await p.waitForTimeout(500);
await p.locator('.big-go').click({ force: true });
await p.waitForTimeout(1200);
await p.locator('.mcard').nth(1).click({ force: true });
await p.waitForTimeout(600);
await p.locator('.detail .big-go').click({ force: true });
await p.waitForTimeout(9000);
const probe = () => p.evaluate(() => ({ page: window.__ss!.page, beat: window.__ss!.beat, phase: window.__ss!.phase, lit: [...document.querySelectorAll('.caption .w')].findIndex((w) => w.classList.contains('on')), words: document.querySelectorAll('.caption .w').length }));
const a = await probe(); console.log('playing:', JSON.stringify(a));
await p.locator('.ctl.pause').click();
await p.waitForTimeout(300);
const b1 = await probe();
await p.waitForTimeout(3000);
const b2 = await probe();
console.log('paused overlay visible:', await p.locator('.paused').isVisible(), '| frozen:', JSON.stringify(b1) === JSON.stringify(b2));
await p.locator('.paused').click({ force: true });
await p.waitForTimeout(2500);
const c = await probe(); console.log('resumed:', JSON.stringify(c));
await p.waitForTimeout(400);
const before = await probe();
await p.locator('.ctl.replay').click();
await p.waitForTimeout(250);
const after = await probe();
console.log('replay: lit word before', before.lit, 'after', after.lit, '| same line:', before.beat === after.beat);
await b.close(); server.close();
