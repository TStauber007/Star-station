// Story data types. Missions are plain JSON files in content/missions/.

export type StateValues = Record<string, string>;

export interface SceneArt {
  place?: string;
  time?: string;
  lights?: string;
  crew?: string;
  robot?: string;
  moon?: string;
  props?: string[];
}

export interface TapMoment {
  effect: string;
  count: number;
}

export interface Beat {
  say: string;
  art?: SceneArt;
  tap?: TapMoment;
  do?: { targets: string };
  if?: StateValues;
  sfx?: string;
}

export interface ChoiceOption {
  card: string;
  label: string;
  say: string;
  next: string;
  set?: StateValues;
}

export interface Choice {
  say: string;
  options: ChoiceOption[];
}

export interface Page {
  art: SceneArt;
  beats: Beat[];
  next?: string;
  choice?: Choice;
  end?: boolean;
}

export interface ParentNotes {
  virtue: string;
  science: string[];
  summary: string;
  paths: { moment: string; options: string[] }[];
  talk: string[];
}

export interface Mission {
  id: string;
  order: number;
  title: string;
  titleSay: string;
  mood: 'day' | 'bedtime';
  speed?: number;
  sticker: string;
  cover: SceneArt;
  parent: ParentNotes;
  state: StateValues;
  start: string;
  pages: Record<string, Page>;
}

// Narration manifest (generated by `npm run narration`).
export interface NarrationClip {
  /** duration in seconds */
  d: number;
  /** words: [start, end, text] */
  w: [number, number, string][];
}

export interface NarrationManifest {
  /** line key -> cast key -> clip id */
  lines: Record<string, Record<string, string>>;
  clips: Record<string, NarrationClip>;
}
